const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),asar=require('@electron/asar'),cp=require('node:child_process');
const source=process.argv[2];if(!source)throw Error('Pass extracted official Chatbox 1.20.3 directory for pinned native dependencies');
const archive=path.join(source,'resources/app.asar');
const hash=crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
if(hash!=='e43647af8168b731caa9afaed269a4700f8686c257fbc4dd6a254da42729fa01')throw Error('Chatbox dependency archive checksum mismatch');
const out=path.resolve('.ai-runtime/Chatbox');fs.mkdirSync(out,{recursive:true});
asar.extractAll(archive,path.join(out,'native'));
for(const name of ['assets','app.asar.unpacked'])fs.cpSync(path.join(source,'resources',name),path.join(out,'resources',name),{recursive:true});
fs.cpSync(path.resolve('integrations/chatbox/node_modules'),path.join(out,'node_modules'),{recursive:true});
fs.copyFileSync(path.resolve('.ai-runtime/chatbox-source/LICENSE'),path.join(out,'CHATBOX-LICENSE.txt'));
cp.execFileSync(process.execPath,[path.resolve('scripts/build-chatbox-source.cjs')],{stdio:'inherit'});
